#!/usr/bin/env python3
# Regenerate stock-abi-users.txt: which stock blobs link a C++ library whose ABI differs
# between stock and the source build (objects laid out by the caller from the library's
# headers, so symbol checks cannot catch it; libtinyxml2 corrupted the display composer's
# stack). extract-files.py gives those blobs a stock copy of the library, <lib>-stock.so,
# installed next to them, and rewrites their DT_NEEDED.
#   gen-stock-abi.py <stock dump> <llvm-readelf>
import os, re, subprocess, sys

LIBS = ['libtinyxml2', 'libjsoncpp', 'libxml2', 'libchrome', 'libflatbuffers-cpp',
        'libaudioserviceexampleimpl', 'libaudioutils', 'libbluetooth_audio_session_aidl',
        'android.hardware.bluetooth.audio-impl']

here = os.path.dirname(os.path.abspath(__file__))
device = os.path.dirname(os.path.dirname(here))
dump, readelf = sys.argv[1], sys.argv[2]

files = []
for line in open(os.path.join(device, 'proprietary-files.txt')):
    line = line.split('#')[0].strip()
    if not line:
        continue
    # read the stock file (src), key the result by the installed name (dst): blob fixups are
    # looked up by dst, and the stock copies themselves link each other
    src, _, dst = line.lstrip('-').split(';')[0].partition(':')
    if src.startswith(('vendor/', 'system_ext/')):
        files.append((dst or src, src))

out = []
for f, src in sorted(set(files)):
    path = os.path.join(dump, src)
    if not os.path.isfile(path) or os.path.islink(path):
        continue
    dyn = subprocess.run([readelf, '-d', path], capture_output=True, text=True).stdout
    needed = set(re.findall(r'NEEDED.*\[([^\]]+)\.so\]', dyn))
    libs = [l for l in LIBS if l in needed and os.path.basename(src) != l + '.so']
    if libs:
        out.append(f + ' ' + ' '.join(libs))

with open(os.path.join(device, 'stock-abi-users.txt'), 'w') as o:
    o.write('# Generated by meta/scripts/gen-stock-abi.py: <blob> <stock libraries it links>\n')
    o.write('\n'.join(out) + '\n')
print(f'{len(out)} blobs')
