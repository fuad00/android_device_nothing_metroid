#!/usr/bin/env bash
# Prepare a synced Kleaf workspace (meta/kernel/metroid-kleaf.xml) for building the metroid kernel.
# Based on logix727/android_device_nothing_metroid kernel/setup-kleaf-workspace.sh (Apache-2.0),
# without its msm-kernel source patches: the B4.1 NothingOSS tree already carries those sources.
#   setup-workspace.sh <kernel-workspace>
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
WS="$(cd "${1:?usage: $0 /path/to/kernel-workspace}" && pwd)"
[[ -f "$WS/msm-kernel/bazel.WORKSPACE" ]] || { echo "no msm-kernel checkout in $WS" >&2; exit 1; }

# Bazel workspace root = msm-kernel's template; dtc builds also need the generated version header
cp "$WS/msm-kernel/bazel.WORKSPACE" "$WS/WORKSPACE"
python3 - "$WS/WORKSPACE" <<'PY'
import re, sys
p = sys.argv[1]; s = open(p).read()
s = s.replace('"version_non_gen.h",\n', '"version_non_gen.h",\n        "version_gen.h",\n')
open(p, 'w').write(s)
PY

# Nothing's rules load TARGET_PRODUCT from @nt_project//:dict.bzl (generated by their build
# environment, not published) to add build.config.nothing.<product> (vendor/Metroid.config, NT_PROJECT)
mkdir -p "$WS/nt_project"
: > "$WS/nt_project/WORKSPACE"
: > "$WS/nt_project/BUILD.bazel"
printf '%s\n' 'TARGET_PRODUCT = "Metroid"' > "$WS/nt_project/dict.bzl"
grep -q 'name = "nt_project"' "$WS/WORKSPACE" || \
  printf '\nlocal_repository(\n    name = "nt_project",\n    path = "nt_project",\n)\n' >> "$WS/WORKSPACE"

# Qualcomm's msm_*.bzl macros live in msm-kernel but are loaded as //build:*.bzl
: > "$WS/build/BUILD"
for name in msm_abl.bzl msm_common.bzl msm_dtc.bzl msm_kernel_16k_la.bzl msm_kernel_extensions.bzl \
        msm_kernel_la.bzl msm_kernel_le.bzl msm_kernel_vm.bzl msm_platforms.bzl; do
  ln -sfn "../msm-kernel/$name" "$WS/build/$name"
done
ln -sfn "msm-kernel/vendor" "$WS/vendor"
printf '%s\n' 'msm-kernel/vendor' 'nothing-modules/qcom' > "$WS/.bazelignore"

# dtc: version header and parser sources that its Android.bp would normally generate
printf '%s\n' '#define DTC_VERSION "DTC 1.7.0"' > "$WS/external/dtc/version_gen.h"
cp "$WS/external/dtc/version_gen.h" "$WS/external/dtc/version_non_gen.h"
bison -b "$WS/external/dtc/dtc-parser" -d "$WS/external/dtc/dtc-parser.y"
cp "$WS/external/dtc/dtc-parser.tab.h" "$WS/external/dtc/dtc-parser.h"

cp "$HERE/vendor-module-targets.txt" "$WS/vendor-module-targets.txt"
echo "Kleaf workspace prepared at $WS"
